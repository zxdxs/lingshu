"""抽幾組病候模板，寫出 data/病候.json。

選這些篇章，是因為它們共用同一個寫法：**病名 → 其候（證）→ 治法／死生**。
  〈厥病〉：厥頭痛（六種）、厥心痛（五藏各一）、真頭痛／真心痛（死不治）
  〈周痹〉：衆痹與周痹之分，及其刺法
  〈水脹〉：水、膚脹、鼓脹、腸覃、石瘕五者之別

每條的句ID 由本檔指定（編者挑選），文句一律取自句索引——挑選可議，引文不可錯。

用法：python3 scripts/build_binghou.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JU = {s['id']: s for s in json.load(open(os.path.join(ROOT, '底本', '靈樞經_句索引.json'),
                                          encoding='utf-8'))['句']}

# (病名, 證候句id list, 治法/死生句id list, 一句註)
