def check_prose_quotes(data):
    """敘述層的「」也當引文驗：≥2 字者必須見於靈樞；1 字者為術語，略過。"""
    sys.path.insert(0, os.path.join(ROOT, 'scripts'))
    from check_quotes import norm
    CH = json.load(open(os.path.join(ROOT, '底本', '靈樞經_81篇.json'), encoding='utf-8'))['篇']
    corpus = norm(''.join(p['經文'] for p in CH))
    miss = []
    for g in data['組']:
        for x in g['條']:
            for k in ('原則', '推演', '用', '界'):
                for q in re.findall(r'「([^」]+)」', x[k]):
                    if len(q) < 2:
                        continue
                    if norm(q) not in corpus:
                        miss.append((x['n'], k, q))
    return miss


def main():
    out, missing = [], []
    for i, L in enumerate(LAW, 1):
        qs = []
        for sid, note in L['引']:
            s = JU.get(sid)
            if not s:
                missing.append(sid)
                continue
            qs.append({'id': sid, 'seq': s['seq'], '篇': s['pian'], '文': s['text'], '註': note})
        out.append({'n': i, '組': L['組'], '名': L['名'], '原則': L['原則'],
                    '引': qs, '推演': L['推演'], '用': L['用'], '界': L['界']})
    if missing:
        raise SystemExit(f'句ID 不存在：{missing}')

    groups = []
    for x in out:
        if not groups or groups[-1]['組'] != x['組']:
            groups.append({'組': x['組'], '條': []})
        groups[-1]['條'].append(x)

    NAME = {p['序']: p['篇名_規範'] for p in
            json.load(open(os.path.join(ROOT, '底本', '靈樞經_81篇.json'), encoding='utf-8'))['篇']}
    route = []
    for r in ROUTE:
        route.append({'階段': r['階段'], '題': r['題'], '為什麼': r['為什麼'],
                      '通則': r['通則'],
                      '篇': [{'序': sq, '名': NAME[sq]} for sq in r['篇'] if sq in NAME]})
    data = {'路徑': route,
            '說明': {'標記': '原＝原文（句ID 可回查）；歸＝編者歸納；空＝未驗或不可推',
                     '來源': '底本/靈樞經_句索引.json',
                     '判準': '一條通則至少要能由兩篇支持；單篇的寫法留在該篇模組，不升為通則。'},
            '條數': len(out), '組數': len(groups), '組': groups}
    p = os.path.join(ROOT, 'data', '通則.json')
    miss = check_prose_quotes(data)
    if miss:
        print('敘述層引文未見於靈樞：')
        for n, k, q in miss:
            print(f'  第 {n} 條・{k}：「{q}」')
    json.dump(data, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'寫出 {p}：{len(out)} 條、{len(groups)} 組；引文 {sum(len(x["引"]) for x in out)} 段')


if __name__ == '__main__':
    main()
