PUNC = '，。、；：？！「」《》'
def sp(x): return ''.join(c for c in x if c not in PUNC and not c.isspace())
for c in DIAN + KUANG:
    assert sp(c['原文']) in sp(T22), c['名']
for c in TONG:
    assert sp(c['文']) in sp(T22), c['名']

# 「舌下少陰」是部位限定語，不是「手少陰」。先排除，避免被前綴繼承誤標。
MER = re.compile(r'(舌下|舌本|頭兩顑|項|腰|足|手)?(太陰|少陰|厥陰|太陽|少陽|陽明)')
def parse_mer(text):
    out, prefix = [], None
    for m in MER.finditer(text):
        loc = m.group(1)
        if loc in ('舌下', '舌本', '頭兩顑', '項', '腰'):
            # 部位語直接連寫，不繼承手／足前綴
            out.append(loc + m.group(2))
            continue
        if loc:
            prefix = loc
        if prefix:
            out.append(prefix + m.group(2))
    return list(dict.fromkeys(out))
for c in DIAN + KUANG:
    c['取經'] = '、'.join(parse_mer(c['治']))

