#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
五心痛訓練模組：把《靈樞·厥病》的五心痛整理成可教學的單元。

結構：原文（L1）→ 白話 → 辨證要點 → 取穴（含五輸屬性）→ 取穴邏輯 → 常見誤區
每條都回填底本字元位置，可回溯。

輸出：data/模組_五心痛.json、docs/12_五心痛訓練模組.md
"""
import json, os, csv

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = {c['序']: c for c in json.load(open(os.path.join(ROOT, '底本', '靈樞經_81篇.json'), encoding='utf-8'))['篇']}
WU = json.load(open(os.path.join(ROOT, 'demo', '本輸_五輸穴示例.json'), encoding='utf-8'))['表']
T = S[24]['經文'].replace('\n', '')
J24 = {c['序']: c for c in json.load(open(os.path.join(ROOT, '底本', '靈樞經_句讀層.json'), encoding='utf-8'))['篇']}[24]['句讀'].replace('\n', '')

SHU = {}
for r in WU:
    for k in ['井', '滎', '輸', '原', '經', '合']:
        v = r.get(k, '—')
        if v not in ('—', '', None):
            SHU[v] = (r['歸屬'], k)

CASES = [
    dict(名='腎心痛',
         原文='厥心痛與背相控善瘈如從後觸其心傴僂者腎心痛也先取京骨崑崙發狂不已取然谷',
         白話='心痛牽引到背部，容易抽搐，像從背後觸動心臟，彎腰駝背的，是腎心痛。先取京骨、崑崙；若發狂不止，再取然谷。',
         要點=['痛與背相控（放射至背）', '善瘈（抽搐）', '傴僂（彎腰前傾，止痛體位）'],
         穴=['京骨', '崑崙', '然谷'],
         邏輯='腎與膀胱相表裡；背為足太陽之分。京骨為膀胱原穴、崑崙為膀胱經穴，然谷為腎經滎穴。',
         誤區='把「傴僂」當成一般體態描述，忽略它是疼痛時的保護性體位。'),
    dict(名='胃心痛',
         原文='厥心痛腹脹胷滿心尤痛甚胃心痛也取之大都大白',
         白話='心痛伴腹脹胸滿，心痛特別劇烈的，是胃心痛。取大都、太白。',
         要點=['腹脹', '胸滿'],
         穴=['大都', '太白'],
         邏輯='脾胃相表裡，腑病取藏經（足太陰脾）。大都為脾滎穴，太白為脾輸兼原穴。',
         誤區='見「胃」字就取足陽明胃經，與經文所取之脾經不符。'),
    dict(名='脾心痛',
         原文='厥心痛痛如以錐鍼刺其心心痛甚者脾心痛也取之然谷大谿',
         白話='心痛像錐子刺一樣，痛得厲害的，是脾心痛。取然谷、太谿。',
         要點=['刺痛（錐刺感）', '心痛劇烈'],
         穴=['然谷', '大谿'],
         邏輯='經文取足少陰腎經穴，與「脾」的對應並不直觀；歷代注家解釋不一，此處暫標待考，不宜強解。',
         誤區='誤以為五心痛必按五行生剋配穴——實則五組中只有部分符合表裡關係。'),
    dict(名='肝心痛',
         原文='厥心痛色蒼蒼如死狀終日不得太息肝心痛也取之行間大衝',
         白話='面色蒼白如死狀，整天不能長嘆息的，是肝心痛。取行間、太衝。',
         要點=['色蒼蒼如死狀', '終日不得太息'],
         穴=['行間', '大衝'],
         邏輯='取本經（足厥陰肝）。行間為肝滎穴，太衝為肝輸兼原穴。',
         誤區='把「不得太息」讀成「善太息」——前者是不能長吁，後者是頻頻嘆氣。'),
    dict(名='肺心痛',
         原文='厥心痛卧若徒居心痛間動作痛益甚色不變肺心痛也取之魚際大淵',
         白話='躺著或閒居時心痛緩解，一動作就痛得更厲害，面色不變的，是肺心痛。取魚際、太淵。',
         要點=['卧若徒居則減', '動作痛益甚', '色不變'],
         穴=['魚際', '大淵'],
         邏輯='取本經（手太陰肺）。魚際為肺滎穴，太淵為肺輸兼原穴。',
         誤區='忽略「色不變」這個鑑別點——它正是與肝心痛「色蒼蒼」相對的關鍵。'),
]

TAIL = [
    dict(名='眞心痛（禁忌）',
         原文='眞心痛手足凊至節心痛甚旦發夕死夕發旦死',
         白話='真心痛，手足冷到關節，心痛劇烈，早晨發作當晚死，晚上發作次日晨死。',
         要點=['手足清至節（陽氣欲絕）', '旦發夕死／夕發旦死'],
         穴=[],
         邏輯='不是配穴問題，是預後判斷。臨床遇此當急救，不可僅以針刺論治。',
         誤區='把真心痛與五心痛並列為同一層次的辨證，忽略其預後意義。'),
    dict(名='心痛不可刺（禁忌）',
         原文='心痛不可刺者中有盛聚不可取于腧',
         白話='心痛不可用刺法的情況：內有盛聚（實邪積聚），不可取腧穴刺之。',
         要點=['中有盛聚'],
         穴=[],
         邏輯='實邪積聚非刺腧所能解，屬刺禁。',
         誤區='凡心痛皆刺，忽略刺禁。'),
]

CANON = {'大谿': '太谿', '大衝': '太衝', '大淵': '太淵', '大抒': '大杼'}
ZANG_YUAN = {'太淵', '大陵', '太衝', '太白', '太谿'}   # 五藏原穴（九鍼十二原）

def shu_of(name):
    m = CANON.get(name, name)
    mer, cat = SHU.get(m, ('?', '?'))
    if m in ZANG_YUAN:
        cat += '（兼原）'
    return mer, cat

allcases = CASES + TAIL
PUNC = '，。、；：？！《》「」'
Z = S[24]['正規化'].replace('\n', '')
stripped, idxmap = [], []
for k, ch in enumerate(J24):
    if ch not in PUNC and not ch.isspace():
        stripped.append(ch); idxmap.append(k)
SJ = ''.join(stripped)
assert SJ == Z, "句讀層去標點後與正規化不一致"

for c in allcases:
    nm = c['名'].replace('（禁忌）', '')
    if nm.startswith('眞'):
        z0 = Z.find('真心痛')
    elif nm.startswith('心痛不可刺'):
        z0 = Z.find('心痛不可刺')
    else:
        z0 = Z.rfind('厥心痛', 0, Z.find(nm))
    assert z0 >= 0, c['名']
    z1 = z0 + len(c['原文']) - 1
    c['原文標點'] = J24[idxmap[z0]:idxmap[z1] + 1]
    c['位置'] = z0

for c in CASES + TAIL:
    i = T.find(c['原文'])
    assert i >= 0, c['名']
    c['位置'] = i
    c['取穴明細'] = [{'穴': CANON.get(n, n), '原文寫法': n,
                        '歸經': shu_of(n)[0], '五輸': shu_of(n)[1]} for n in c['穴']]

mod = {
    '模組': '五心痛辨證配穴',
    '出處': {'篇序': 24, '篇名': '厥病'},
    '學習目標': ['能依證候描述辨出五心痛中的哪一型',
             '能說出各型的取穴與其五輸屬性',
             '知道真心痛與心痛刺禁的臨床意義'],
    '層級': 'L1 經文 → 白話 → 辨證要點 → 取穴 → 誤區',
    '證型': CASES,
    '禁忌': TAIL,
    '使用建議': '先讀原文，遮住白話自行解讀；再看要點核對；最後做題。每次 5–8 分鐘。',
}
json.dump(mod, open(os.path.join(ROOT, 'data', '模組_五心痛.json'), 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)

# ---------------- 學習者版 ----------------
with open(os.path.join(ROOT, 'docs', '12_五心痛訓練模組.md'), 'w', encoding='utf-8') as f:
    f.write('# 五心痛辨證配穴（訓練模組）\n\n')
    f.write('> 出處：《靈樞·厥病第二十四》\n')
    f.write('> 用法：先讀原文，遮住白話自行解讀；再看辨證要點核對；最後做題。每次 5–8 分鐘。\n\n---\n\n')
    f.write('## 一、原文（底本）\n\n')
    for c in CASES + TAIL:
        f.write(f"> {c['原文標點']}\n\n")
    f.write('---\n\n## 二、五心痛\n\n')
    for c in CASES:
        f.write(f"### {c['名']}\n\n")
        f.write(f"**原文**：{c['原文標點']}\n\n")
        f.write(f"**白話**：{c['白話']}\n\n")
        f.write('**辨證要點**：' + '；'.join(c['要點']) + '\n\n')
        f.write('**取穴**：' + '、'.join(
            f"{d['穴']}（{d['歸經']}·{d['五輸']}）" for d in c['取穴明細']) + '\n\n')
        f.write(f"**取穴邏輯**：{c['邏輯']}\n\n")
        f.write(f"**常見誤區**：{c['誤區']}\n\n")
    f.write('---\n\n## 三、兩個禁忌\n\n')
    for c in TAIL:
        f.write(f"### {c['名']}\n\n**原文**：{c['原文']}\n\n**白話**：{c['白話']}\n\n")
        f.write(f"**要點**：{'；'.join(c['要點'])}\n\n**說明**：{c['邏輯']}\n\n**誤區**：{c['誤區']}\n\n")
    f.write('---\n\n## 四、鑑別速查\n\n')
    f.write('| 證型 | 關鍵鑑別點 | 取穴 |\n|---|---|---|\n')
    for c in CASES:
        f.write(f"| {c['名']} | {c['要點'][0]} | " +
                '、'.join(d['穴'] for d in c['取穴明細']) + " |\n")
    f.write('\n> **注意**：五心痛的配穴不套用單一五行公式。腎心痛取膀胱經（表裡）、'
            '胃心痛取脾經（表裡）、肝與肺心痛取本經，而脾心痛取腎經一點，注家未有定論，'
            '本模組標為待考，不強解。\n')

print("模組建立完成：", len(CASES), "證型 +", len(TAIL), "禁忌")
for c in CASES:
    print(f"  {c['名']}: {c['取穴明細']}")
