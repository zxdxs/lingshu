#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""治則模組：〈病本〉的標本先後。

為什麼單獨立一個模組：docs/36 指出，《類經》把「標本」單列一類（5 條），
而本專案的 11 個模組完全沒有它的位置——〈病本〉185 字被稀釋在診法模組裡。
一個概念沒有專屬模組，就會消失。
"""
import json, os, re, csv

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIAN = {int(p['序']): p for p in json.load(open(os.path.join(ROOT, '底本', '靈樞經_81篇.json'), encoding='utf-8'))['篇']}
T = PIAN[25]['正規化']

# (條件, 治法, 原文片段, 備註)
RULES = [
    ('先病而後逆', '治其本', '先病而後逆者治其本', ''),
    ('先逆而後病', '治其本', '先逆而後病者治其本', ''),
    ('先寒而後生病', '治其本', '先寒而後生病者治其本', ''),
    ('先病而後生寒', '治其本', '先病而後生寒者治其本', ''),
    ('先熱而後生病', '治其本', '先熱而後生病者治其本', ''),
    ('先泄而後生他病', '治其本（且先調之）', '先泄而後生他病者治其本必且調之乃治其他病',
     '原文「必且調之，乃治其他病」'),
    ('先病而後中滿', '治其標', '先病而後中滿者治其標', '中滿為急，故先治標'),
    ('先病後泄', '治其本', '先病後泄者治其本', ''),
    ('先中滿而後煩心', '治其本', '先中滿而後煩心者治其本', ''),
    ('大小便不利', '治其標', '大小便不利治其標', '二便不通為急'),
    ('大小便利', '治其本', '大小便利治其本', ''),
    ('病發而有餘', '先治其本，後治其標', '病發而有餘本而標之先治其本後治其標',
     '「本而標之」＝先本後標'),
    ('病發而不足', '先治其標，後治其本', '病發而不足標而本之先治其標後治其本',
     '「標而本之」＝先標後本'),
    ('先大小便不利而後生他病', '治其本', '先小大便不利而後生他病者治其本也',
     '與「大小便不利治其標」看似相反，實則此處以二便不利為本'),
]


def main():
    bad = [r for r in RULES if r[2] not in T]
    if bad:
        for b in bad:
            print('✗ 不見於原文:', b[2])
        raise SystemExit(f'校驗失敗 {len(bad)} 條')

    mod = {
        '模組': '標本與治則',
        '出處': {'篇序': 25, '篇名': '病本'},
        '學習目標': ['分清何時治本、何時治標', '理解「本而標之」「標而本之」的差別',
                 '知道二便不利為何先治', '知道「間者並行，甚者獨行」'],
        '規則': [{'條件': a, '治法': b, '原文': c, '備註': d} for a, b, c, d in RULES],
        '通則': [{'條': '間者並行，甚者獨行', '原文': '謹詳察間甚以意調之間者并行甚為獨行',
                  '說明': '病情間緩者可標本並治，甚急者須專治一處'}],
        '校記': [
            '「本而標之」「標而本之」舊解不一：一般讀作「以本为主而兼治標」「以標为主而兼治本」，'
            '本文從「有餘先本、不足先標」的句式取義，未強作定論。',
            '「大小便不利治其標」與末句「先小大便不利而後生他病者治其本」並存；'
            '前者以他病為本、二便為標，後者以二便為本，前提不同則結論不同，非自相矛盾。',
            '「客氣」「同氣」原文未釋，存而不解。',
        ],
    }
    json.dump(mod, open(os.path.join(ROOT, 'data', '模組_治則.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print(f'治則規則 {len(RULES)} 條，全部通過原文校驗')


if __name__ == '__main__':
    main()
