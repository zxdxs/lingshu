# 異體字形對照：僅限同字異寫，不含語義上有別的（如 己/已/巳）不可混
VAR = {'乗': '乘', '曚': '矇', '凊': '清', '摶': '搏', '闗': '關', '産': '產',
       '爲': '為', '來': '來', '衇': '脈', '脉': '脈', '痺': '痹', '寫': '瀉'}


def vn(x):
    return ''.join(VAR.get(c, c) for c in x)


def locate(txt, q):
    """歸一後定位，回傳原文中的同一段（索引一一對應）。"""
    t, qq = vn(txt), vn(q)
    i = t.find(qq)
    if i < 0:
        return None
    return txt[i:i + len(q)]


def main():
    bad, out = [], []
    for code, n, cat, text, who, note in ROWS:
        src = PIAN[n]['正規化'].replace('\n', '')
        hit = locate(src, text)
        if hit is None:
            bad.append((code, n, text))
            continue
        out.append({'編號': code, '篇序': n, '篇名': PIAN[n]['篇名_規範'], '類別': cat,
                    '條文': hit, '適用對象': who, '說明': note})
    if bad:
        for b in bad:
            print('✗ 不見於原文:', b)
        raise SystemExit(f'校驗失敗 {len(bad)} 條')
    with open(os.path.join(ROOT, 'data', '禁忌清單.csv'), 'w', encoding='utf-8-sig', newline='') as f:
        wr = csv.DictWriter(f, fieldnames=['編號', '篇序', '篇名', '類別', '條文', '適用對象', '說明'])
        wr.writeheader()
        wr.writerows(out)

    from collections import Counter
    print(f'禁忌條文 {len(out)} 條，全部通過原文校驗')
    print('類別:', dict(Counter(r['類別'] for r in out)))
    print('適用對象:', dict(Counter(r['適用對象'] for r in out)))
    print('涉及篇:', sorted({r['篇序'] for r in out}))


if __name__ == '__main__':
    main()
