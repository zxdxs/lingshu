def main():
    groups, missing = [], []
    for g in GROUPS:
        rows = []
        for sid, note in g['條']:
            s = JU.get(sid)
            if not s:
                missing.append(sid)
                continue
            rows.append({'id': sid, '篇': s['pian'], '文': s['text'], '註': note})
        groups.append({'組': g['組'], '問題': g['問題'], '條': rows, '差': g['差'], '用': g['用']})
    if missing:
        raise SystemExit(f'句ID 不存在：{sorted(set(missing))}')
    data = {'說明': {'做法': '組與句ID 由編者挑；文句取自句索引', '組數': len(groups),
                     '條數': sum(len(g['條']) for g in groups)},
            '組': groups}
    p = os.path.join(ROOT, 'data', '變體.json')
    json.dump(data, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'寫出 {p}：{len(groups)} 組、{data["說明"]["條數"]} 句')


if __name__ == '__main__':
    main()
