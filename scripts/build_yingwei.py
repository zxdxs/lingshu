#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""抽營衛資料，寫出 data/營衛.json。

三塊：
  定義：〈營衛生會〉清者為營、濁者為衛；營在脉中、衛在脉外；五十而復大會。
  衛氣：一日一夜五十周於身，晝行陽二十五、夜行陰二十五；平旦出於目的路線（六句）。
  營氣：〈營氣〉一段連續文字給出十二經的營行次序；另附編者依原文提煉的步驟表（標『歸』）。

文句取自句索引；次序表是編者整理，不是原文格式。

用法：python3 scripts/build_yingwei.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JU = {s['id']: s for s in json.load(open(os.path.join(ROOT, '底本', '靈樞經_句索引.json'),
                                          encoding='utf-8'))['句']}

DEF = ['18-2-1', '18-2-2', '18-2-3']
WEI_TOTAL = ['76-2-4', '18-2-4']
WEI_DAY = ['76-3-1', '76-3-2', '76-3-3', '76-3-4', '76-3-5', '76-3-6']
YING_TEXT = ['16-1-1', '16-2-1', '16-2-2', '16-2-3']
WEI_NIGHT = ['76-5-1', '76-6-1', '76-6-2', '76-6-3']
WEI_TIME = ['76-8-2', '76-8-3', '76-8-5', '76-8-6', '76-8-9']

# 編者依〈營氣〉原文提煉的次序（原文是一段連續敘述，此表是整理）
YING_ORDER = [
 ('1', '手太陰', '氣從太陰出', '16-2-1'),
 ('2', '手陽明', '注手陽明', '16-2-1'),
 ('3', '足陽明', '上行注足陽明，下行至跗上，注大指間，與太陰合', '16-2-1'),
 ('4', '足太陰', '與太陰合；上行抵髀，從脾注心中', '16-2-1'),
 ('5', '手少陰', '循手少陰，出腋，下臂，注小指', '16-2-1'),
 ('6', '手太陽', '合手太陽；上行乗腋，出䪼內，注目內眥，上巔，下項', '16-2-1'),
 ('7', '足太陽', '合足太陽；循脊，下尻，下行注小指之端', '16-2-1'),
 ('8', '足少陰', '循足心，注足少陰；上行注腎，從腎注心', '16-2-1'),
 ('9', '手厥陰（心主）', '循心主脉，出腋，下臂，入掌中，出中指之端', '16-2-1'),
 ('10', '手少陽', '合手少陽；上行注膻中，散于三焦', '16-2-1'),
 ('11', '足少陽', '従三焦注膽，出脇，注足少陽', '16-2-1'),
 ('12', '足厥陰', '合足厥陰，上行至肝，從肝上注肺', '16-2-1'),
 ('13', '手太陰（復出）', '下注肺中，復出太陰', '16-2-2'),
]


def grab(ids):
    out = []
    for i in ids:
        if i not in JU:
            raise SystemExit(f'句ID 不存在：{i}')
        out.append({'id': i, '文': JU[i]['text']})
    return out


def main():
    data = {
        '說明': {'來源': '〈營氣〉〈營衛生會〉〈衛氣行〉',
                 '重點': '營在脉中、衛在脉外；衛氣晝夜各二十五周；營氣十二經次序為編者依原文提煉'},
        '定義': grab(DEF),
        '衛氣': {'總數': grab(WEI_TOTAL), '平旦': grab(WEI_DAY),
                 '夜行': grab(WEI_NIGHT), '候時': grab(WEI_TIME)},
        '營氣': {'原文': grab(YING_TEXT),
                 '次序': [{'步': a, '經': b, '據': c, 'id': d} for a, b, c, d in YING_ORDER]},
    }
    p = os.path.join(ROOT, 'data', '營衛.json')
    json.dump(data, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'寫出 {p}：定義 {len(data["定義"])}、衛氣 {len(WEI_TOTAL)}+{len(WEI_DAY)}、營氣 {len(YING_ORDER)} 步')


if __name__ == '__main__':
    main()
